def section_of(page: str) -> str | None:
    """Which top-level menu item owns this page."""
    for label, hub, subs in MENU:
        if page == hub or page in [s[1] for s in subs]:
            return label
    for label, hub, subs in MENU:                       # directory fallback
        d = os.path.dirname(hub)
        if d and page.startswith(d + "/"):
            return label
    return None



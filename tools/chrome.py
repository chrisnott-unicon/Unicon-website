# -------------------------------------------------------------------- apply
def balanced(s: str, i: int, tag: str) -> int:
    depth = 0
    for m in re.finditer(rf"<{tag}\b|</{tag}>", s[i:]):
        depth += -1 if m.group(0).startswith("</") else 1
        if depth == 0:
            return i + m.end()
    raise SystemExit(f"unbalanced <{tag}>")


def pages() -> list[str]:
    out = []
    for f in sorted(glob.glob(os.path.join(ROOT, "**", "*.html"), recursive=True)):
        rel = os.path.relpath(f, ROOT).replace(os.sep, "/")
        s = open(f, encoding="utf-8").read()
        if 'http-equiv="refresh"' in s or rel == "404.html":
            continue                                    # redirect stubs and the 404 keep their own markup
        out.append(rel)
    return out


def install_markers(s: str) -> str:
    """One-time: wrap the existing nav and footer in markers."""
    if NAV_START not in s and '<nav id="navbar"' in s:
        i = s.index('<nav id="navbar"')
        i = s.rfind("\n", 0, i) + 1
        j = balanced(s, i, "nav")
        s = s[:i] + NAV_START + "\n" + s[i:j] + "\n    " + NAV_END + s[j:]
    if FOOT_START not in s and "<footer" in s:
        i = s.index("<footer")
        i = s.rfind("\n", 0, i) + 1
        j = balanced(s, i, "footer")
        s = s[:i] + FOOT_START + "\n" + s[i:j] + "\n    " + FOOT_END + s[j:]
    return s


def replace(s: str, start: str, end: str, body: str) -> str:
    return re.sub(re.escape(start) + r".*?" + re.escape(end),
                  lambda _m: start + "\n" + body + "\n    " + end, s, flags=re.S)


def render(page: str, s: str) -> str:
    if NAV_START in s:
        s = replace(s, NAV_START, NAV_END, nav(page))
    if FOOT_START in s:
        s = replace(s, FOOT_START, FOOT_END, footer(page))
    return s


def main() -> None:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    changed, missing = [], []
    for page in pages():
        path = os.path.join(ROOT, page)
        s = old = open(path, encoding="utf-8").read()
        if cmd == "init":
            s = install_markers(s)
        if NAV_START not in s or FOOT_START not in s:
            missing.append(page)
        s = render(page, s)
        if s != old:
            changed.append(page)
            if cmd != "check":
                open(path, "w", encoding="utf-8").write(s)

    if missing:
        print("Pages without chrome markers (run 'init'):", file=sys.stderr)
        for p in missing:
            print("  -", p, file=sys.stderr)
    if cmd == "check":
        if changed or missing:
            print(f"\n{len(changed)} page(s) have stale chrome. Run 'python3 tools/chrome.py build'.",
                  file=sys.stderr)
            for p in changed:
                print("  -", p, file=sys.stderr)
            sys.exit(1)
        print(f"chrome is current on {len(pages())} pages.")
    else:
        print(f"{cmd}: {len(changed)} page(s) updated, {len(pages())} checked.")
        if missing:
            sys.exit(1)


if __name__ == "__main__":
    main()

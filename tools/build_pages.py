# A private homeowner is not a corporate reference. Their name does not belong
# on a public capability page, so it is shown as "Private client" instead.
PRIVATE = re.compile(r"^(dr|mr|mrs|ms|prof)[\s.&]|&\s*mrs|^house\s", re.IGNORECASE)


def client_name(n: str) -> str:
    return "Private client" if n and PRIVATE.search(n) else n


def e(x) -> str:
    return html.escape(str(x), quote=True)


def img(pair, cls, eager=False):
    src, alt = pair
    return (f'<img src="{RAW}{src}" alt="{e(alt)}" class="{cls}" '
            f'loading="{"eager" if eager else "lazy"}" decoding="async">')


# ------------------------------------------------------------------ the data
def load_projects():
    spec = importlib.util.spec_from_file_location("pp", os.path.join(ROOT, "tools", "projects_page.py"))
    pp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pp)
    rows = []
    for r in pp.DB:
        if pp.clean(r.get("Status")) in ("Cancelled", "Suspended"):
            continue
        rows.append({
            "name": pp.clean(r.get("Project Name")),
            "desc": pp.clean(r.get("Description")),
            "employer": client_name(pp.clean(r.get("Project Employer"))),
            "year": (pp.clean(r.get("Start")) or "")[:4],
            "months": pp.clean(r.get("Duration (M)")),
            "band": r.get("_band", ""),
            "status": pp.clean(r.get("Status")),
            "appointment": pp.clean(r.get("Appointment Type")),
            "contract": pp.clean(r.get("Contract Format")),
            "sector": pp.sector_of(r),
            "_t": " ".join([pp.clean(r.get("Project Name")), pp.clean(r.get("Description")),
                            pp.clean(r.get("Project Keywords"))]).lower(),
        })
    return rows


def select(rows, sel):
    """Pick the projects that count as evidence for a page."""
    out = []
    for r in rows:
        if sel.get("exclude") and any(w in r["_t"] for w in sel["exclude"]):
            continue
        hit = False
        if sel.get("sectors") and r["sector"] in sel["sectors"]:
            hit = True
        if sel.get("employers") and r["employer"] in sel["employers"]:
            hit = True
        if sel.get("any") and any(w in r["_t"] for w in sel["any"]):
            hit = True
        if hit:
            out.append(r)
    out.sort(key=lambda r: (r["year"] or "0000"), reverse=True)
    return out



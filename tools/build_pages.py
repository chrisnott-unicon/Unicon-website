def hub(content, rows) -> str:
    cards = ""
    for slug, c in content.items():
        if slug.startswith("_"):
            continue
        title, icon, blurb = HUB_BLURB[slug]
        n = len(select(rows, c["select"]))
        tag = (f'<span class="font-mono text-[9px] uppercase tracking-widest text-unicon-green">'
               f'{n} project{"s" if n != 1 else ""} delivered</span>' if n else
               '<span class="font-mono text-[9px] uppercase tracking-widest text-gray-400">Capability, no delivered projects yet</span>')
        cards += f'''
                <a href="{BASE}/build/{slug}.html" target="_top" class="group flex flex-col border border-unicon-border bg-white p-8 transition-colors hover:border-unicon-green">
                    <i class="fa-solid {icon} mb-5 text-2xl text-unicon-green"></i>
                    <h3 class="mb-2 text-lg font-bold uppercase tracking-tight text-unicon-black group-hover:text-unicon-green">{title}</h3>
                    <p class="mb-5 flex-grow text-sm font-light leading-relaxed text-gray-600">{blurb}</p>
                    {tag}
                </a>'''
    total = len(rows)
    return f'''    <section class="border-b border-unicon-border bg-unicon-slate py-16 md:py-24">
        <div class="mx-auto max-w-[90rem] px-6 sm:px-8 lg:px-12">
            <div class="mb-12 max-w-3xl">
                <p class="mb-3 font-mono text-[10px] uppercase tracking-widest text-unicon-green">The Build Division</p>
                <h2 class="text-3xl font-extrabold uppercase leading-none tracking-tight sm:text-4xl md:text-5xl">Eight Disciplines, One Contractor.</h2>
                <p class="mt-6 text-base font-light leading-relaxed text-gray-600 md:text-lg">
                    {total} projects delivered since 1991. Each page below sets out the scope our teams
                    execute, the method we use and the projects behind it &mdash; drawn from the project
                    database rather than written for a brochure. Where we have not built in a sector yet,
                    the page says so.
                </p>
            </div>
            <div class="grid grid-cols-1 gap-6 sm:grid-cols-2 lg:grid-cols-4">{cards}
            </div>
        </div>
    </section>'''


def body(slug, c, rows):
    picked = select(rows, c["select"])
    return "\n\n".join([hero(slug, c), intro(c), scope(c), record(slug, c, picked, rows),
                        method(c), capacity(c, rows), related(c), cta(c)])


def install_markers(s: str) -> str:
    i = s.index(NAV_END) + len(NAV_END)
    j = s.index(FOOT_START)
    return s[:i] + "\n\n    " + START + "\n" + END + "\n\n    " + s[j:]


def main() -> None:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    content = json.load(open(DATA, encoding="utf-8"))
    rows = load_projects()
    changed = []
    for slug, c in content.items():
        if slug.startswith("_"):
            continue
        path = os.path.join(ROOT, "build", slug + ".html")
        s = old = open(path, encoding="utf-8").read()
        if START not in s:
            s = install_markers(s)
        s = re.sub(re.escape(START) + r".*?" + re.escape(END),
                   lambda _m: START + "\n" + body(slug, c, rows) + "\n    " + END, s, flags=re.S)
        if s != old:
            changed.append(slug)
            if cmd != "check":
                open(path, "w", encoding="utf-8").write(s)

    # the Build hub page indexes all eight
    hub_path = os.path.join(ROOT, "build.html")
    hs = ho = open(hub_path, encoding="utf-8").read()
    hs = re.sub(re.escape(HUB_START) + r".*?" + re.escape(HUB_END),
                lambda _m: HUB_START + "\n" + hub(content, rows) + "\n    " + HUB_END, hs, flags=re.S)
    if hs != ho:
        changed.append("build.html (hub)")
        if cmd != "check":
            open(hub_path, "w", encoding="utf-8").write(hs)

    if cmd == "check":
        if changed:
            print("These Build pages are out of date. Run 'python3 tools/build_pages.py build':",
                  file=sys.stderr)
            for x in changed:
                print("  -", x, file=sys.stderr)
            sys.exit(1)
        print(f"{len(content) - 1} Build pages are current.")
    else:
        for slug, c in content.items():
            if slug.startswith("_"):
                continue
            picked = select(rows, c["select"])
            print(f"  {slug:<28} {len(picked):>3} project(s) of evidence"
                  + ("  [no delivered work - evidence note shown]" if not picked else ""))
        print(f"{len(changed)} page(s) written.")


if __name__ == "__main__":
    main()

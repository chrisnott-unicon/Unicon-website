# Plain-language meaning of each contract family.
CONTRACT = [
    ("JBCC", "the Joint Building Contracts Committee Principal Building Agreement, the standard "
             "contract for building work in South Africa"),
    ("GCC", "the General Conditions of Contract for Construction Works, the standard contract "
            "for civil engineering and water infrastructure"),
]


def e(x) -> str:
    return html.escape(str(x), quote=True)


def month(s: str) -> str:
    y, m = s.split("-")[:2]
    return date(int(y), int(m), 1).strftime("%b %Y")


def appt_label(c, r) -> str:
    return c.get("appointment_label") or APPOINTMENT[r["appointment"]]["label"]


def contract_note(fmt: str) -> str:
    for key, text in CONTRACT:
        if fmt.startswith(key):
            return f"{fmt} is {text}."
    return ""


def load():
    content = json.load(open(DATA, encoding="utf-8"))
    rows = {r["name"]: r for r in json.load(open(DB, encoding="utf-8"))["projects"]}
    out = {}
    for slug, c in content.items():
        if slug.startswith("_"):
            continue
        if c["db"] not in rows:
            raise SystemExit(f"{slug}: '{c['db']}' is not in tools/projects.json")
        out[slug] = (c, rows[c["db"]])
    return out


def url(slug: str) -> str:
    return f"{BASE}/{OUT}/{slug}.html"


def cdn(src: str, w: int = 1400) -> str:
    return f"https://wsrv.nl/?url=raw.githubusercontent.com/chrisnott-unicon/{src}&w={w}&output=webp&q=75"


def facts(c, r):
    rows = [
        ("Appointment", appt_label(c, r)),
        ("Contract form", r["contract_format"]),
        ("Programme", f"{month(r['start'])} to {month(r['complete'])} ({r['duration_months']} months)"),
        ("Value band", r["band"].replace("-", "–")),
        ("Employer", c.get("employer_label") or (c["brands"][0]["name"] if c["brands"][0]["role"] in ("Client", "Employer") else r["employer"])),
        ("Sector", c["sector"]),
    ]
    if c["location"]:
        rows.insert(2, ("Location", c["location"]))
    if c["status_label"]:
        rows.append(("Status", c["status_label"]))
    return rows



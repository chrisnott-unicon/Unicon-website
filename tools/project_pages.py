def body(slug, c, r, everything):
    return "\n\n".join([hero(slug, c, r), overview(c, r), appointment(c, r), scope(c),
                        brands(c), capabilities(c), faq(c), related(c, everything), cta()])


# ------------------------------------------------------------------ render
def keep(old: str, start: str, end: str, empty: str) -> str:
    """Whatever a downstream generator wrote inside its markers survives."""
    m = re.search(re.escape(start) + r".*?" + re.escape(end), old or "", flags=re.S)
    return m.group(0) if m else empty


def render(slug, c, r, everything, old: str) -> str:
    shell = open(SHELL, encoding="utf-8").read()
    ogimg = f"https://raw.githubusercontent.com/chrisnott-unicon/{c['image']['src']}"
    tokens = {
        "@@TITLE@@": e(c["title"]), "@@OGTITLE@@": e(c["title"]), "@@DESC@@": e(c["description"]),
        "@@URL@@": url(slug), "@@OGIMG@@": e(ogimg), "@@WAMSG@@": quote(c["wa"], safe=""),
        "@@SCHEMA@@": keep(old, SCHEMA_START, SCHEMA_END, SCHEMA_START + "\n    " + SCHEMA_END),
        "@@NAV@@": keep(old, NAV_START, NAV_END, NAV_START + "\n    " + NAV_END),
        "@@FOOTER@@": keep(old, FOOT_START, FOOT_END, FOOT_START + "\n    " + FOOT_END),
        "@@BODY@@": BODY_START + "\n" + body(slug, c, r, everything) + "\n    " + BODY_END,
    }
    for k, v in tokens.items():
        shell = shell.replace(k, v)
    return shell


def main() -> None:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    everything = load()
    os.makedirs(os.path.join(ROOT, OUT), exist_ok=True)
    changed = []
    for slug, (c, r) in everything.items():
        path = os.path.join(ROOT, OUT, slug + ".html")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        new = render(slug, c, r, everything, old)
        if new != old:
            changed.append(slug)
            if cmd != "check":
                open(path, "w", encoding="utf-8").write(new)
    if cmd == "check":
        if changed:
            print("These project pages are out of date. Run 'python3 tools/project_pages.py build':", file=sys.stderr)
            for s in changed:
                print("  -", s, file=sys.stderr)
            sys.exit(1)
        print(f"{len(everything)} project pages are current.")
    else:
        print(f"{len(changed)} project page(s) written of {len(everything)}.")


if __name__ == "__main__":
    main()

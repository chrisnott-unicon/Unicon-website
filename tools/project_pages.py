ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://www.uniconsa.co.za"
DATA = os.path.join(ROOT, "tools", "project_pages.json")
SHELL = os.path.join(ROOT, "tools", "project_shell.tpl")
DB = os.path.join(ROOT, "tools", "projects.json")
OUT = "projects"

SCHEMA_START = "<!-- SCHEMA:START - generated by tools/schema.py, do not edit by hand -->"
SCHEMA_END = "<!-- SCHEMA:END -->"
NAV_START = "<!-- CHROME:NAV:START - generated by tools/chrome.py, do not edit by hand -->"
NAV_END = "<!-- CHROME:NAV:END -->"
FOOT_START = "<!-- CHROME:FOOTER:START - generated by tools/chrome.py, do not edit by hand -->"
FOOT_END = "<!-- CHROME:FOOTER:END -->"
BODY_START = "<!-- PROJECT:BODY:START - generated by tools/project_pages.py, do not edit by hand -->"
BODY_END = "<!-- PROJECT:BODY:END -->"


#!/usr/bin/env python3
"""Generate the flagship project pages in projects/.

The project database lists ninety-odd projects in one searchable table, which is
good for browsing and poor for search: a tender evaluator or an engine looking for
"post-tensioned reservoir contractor" or "JBCC construction manager retail" finds
no page that answers it. These pages give each of the eight flagship projects its
own address, with the appointment type, the contract form, the recorded scope and
the national brands involved.

Facts (dates, contract form, appointment, value band, employer) are read from
tools/projects.json by project name, so they cannot drift from the database.
Narrative content lives in tools/project_pages.json. The shared head, navigation,
footer and script are the same as every other page: the navigation and footer are
filled by tools/chrome.py and the structured data by tools/schema.py, so this
generator leaves those marker blocks alone and keeps whatever they hold.

Honesty rules, as in tools/build_pages.py: nothing is shown that the database or
the content file does not support, monetary values appear as bands only, and a
photograph that is representative rather than of the site is labelled as such.

Run before chrome.py, schema.py and sitemap.py.

Usage:
    python3 tools/project_pages.py build     write the pages
    python3 tools/project_pages.py check     fail if any page is out of date
"""
